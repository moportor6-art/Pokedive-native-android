// Esquemas del estado de la expedición: copiados campo por campo del juego (townArt), en el mismo orden,
// porque el cliente comprueba que coincidan (hash del protocolo).
import { schema, t } from "@colyseus/schema";
export const QMIN = -512, QMAX = 1536;
const Q = () => t.quantized({ min: QMIN, max: QMAX });
const CD = () => t.quantized({ min: 0, max: 64 });
const F = () => t.float32();
export const
  Player = schema(
    {
      name: t.string(),
      species: t.string(),
      shiny: t.boolean(),
      pact: t.string(),
      trick: t.boolean(),
      costume: t.string(),
      x: Q(),
      y: Q(),
      dir: t.uint8(),
      moving: t.boolean(),
      hp: F(),
      maxHp: t.uint32(),
      downed: t.boolean(),
      revive: F(),
      wet: t.boolean(),
      paralyzed: t.boolean(),
      burning: t.boolean(),
      poisoned: t.boolean(),
      shielded: t.boolean(),
      stunned: t.boolean(),
      dodging: t.boolean(),
      seq: t.uint32(),
      vx: F(),
      vy: F(),
      dodgeT: F(),
      dodgeX: F(),
      dodgeY: F(),
      dashing: t.boolean(),
      holdT: F(),
      frozen: t.boolean(),
      cd1: CD(),
      cd2: CD(),
      cdDodge: CD(),
      anim: t.string(),
      animSeq: t.uint16(),
      level: t.uint16(),
      xp: t.uint16(),
      xpNext: t.uint16(),
      learn: t.string(),
      learnPending: t.uint8(),
      resting: t.boolean(),
      carried: t.string(),
      carriedSafe: t.uint16(),
      coinsSafe: t.uint32(),
      evoTo: t.string(),
      evoT: F(),
      evolved: t.uint8(),
      upgrades: t.string(),
      bag: t.string(),
      speed: t.number(),
      dodgeCd: t.number(),
      specials: t.string(),
      specialLv: t.string(),
      mastery: t.string(),
      away: t.boolean(),
      ult: F(),
      basicCd: F(),
      frenzy: t.boolean(),
      basicAlt: t.boolean(),
      ready: t.boolean(),
      leaves: t.string(),
      cosm: t.string(),
    },
    `Player`,
  ),
  Enemy = schema(
    {
      kind: t.string(),
      species: t.string(),
      x: Q(),
      y: Q(),
      dir: t.uint8(),
      flying: t.boolean(),
      hp: F(),
      maxHp: t.uint32(),
      dead: t.boolean(),
      wet: t.boolean(),
      paralyzed: t.boolean(),
      burning: t.boolean(),
      poisoned: t.boolean(),
      frozen: t.boolean(),
      anim: t.string(),
      animSeq: t.uint16(),
      alpha: t.boolean(),
      boss: t.boolean(),
      elite: t.string(),
      phase: t.boolean(),
      tele: t.string(),
      teleT: CD(),
      teleMax: CD(),
      aimX: Q(),
      aimY: Q(),
      teleSize: t.number(),
      rare: t.boolean(),
      calm: t.uint8(),
      tired: t.boolean(),
      shiny: t.boolean(),
    },
    `Enemy`,
  ),
  Projectile = schema(
    {
      x: Q(),
      y: Q(),
      look: t.string(),
      hostile: t.boolean(),
      owner: t.string(),
      shot: t.uint32(),
      k: t.uint8(),
      target: t.string(),
    },
    `Projectile`,
  ),
  Pickup = schema(
    {
      kind: t.string(),
      x: Q(),
      y: Q(),
      price: t.uint16(),
      lock: t.string(),
      sale: t.boolean(),
      buyer: t.string(),
    },
    `Pickup`,
  ),
  Fog = schema({ x: Q(), y: Q(), r: t.uint8() }, `Fog`),
  ExpeditionState = schema(
    {
      region: t.string(),
      floor: t.uint16(),
      biome: t.string(),
      seed: t.uint32(),
      phase: t.string(),
      stairsX: t.number(),
      stairsY: t.number(),
      rescueSpecies: t.string(),
      rescueX: Q(),
      rescueY: Q(),
      rescued: t.boolean(),
      escort: t.string(),
      rescueHp: F(),
      rescueMaxHp: t.uint32(),
      rescueLost: t.boolean(),
      rescueShiny: t.boolean(),
      rescueCover: t.boolean(),
      rescueShieldT: CD(),
      ropeX: t.number(),
      ropeY: t.number(),
      ropeT: F(),
      rescuedTotal: t.uint16(),
      host: t.string(),
      roster: t.string(),
      shopX: t.number(),
      shopY: t.number(),
      legend: t.string(),
      challenge: t.string(),
      tutorial: t.boolean(),
      mansion: t.boolean(),
      raid: t.string(),
      lanterns: t.string(),
      graves: t.string(),
      coins: t.uint32(),
      combo: t.uint16(),
      comboT: t.quantized({ min: 0, max: 1 }),
      event: t.string(),
      hms: t.string(),
      landmarkUsed: t.boolean(),
      mods: t.map(`uint8`),
      players: t.map(Player),
      enemies: t.map(Enemy),
      projectiles: t.map(Projectile),
      pickups: t.map(Pickup),
      route: t.string(),
      camps: t.string(),
      flip: t.boolean(),
      marks: t.string(),
      fog: t.array(Fog),
      pausedBy: t.string(),
      menus: t.uint8(),
      version: t.uint32(),
      berries: t.uint16(),
      materials: t.uint16(),
      crystals: t.uint16(),
      candies: t.uint16(),
      tickets: t.uint16(),
      ticketsSafe: t.uint16(),
      kills: t.uint32(),
      alphas: t.uint16(),
      bestCombo: t.uint16(),
      runSecs: t.uint32(),
      origin: t.boolean(),
    },
    `ExpeditionState`,
  ),
  Fog_ = Fog;
export const SCHEMAS = [Player, Enemy, Projectile, Pickup, ExpeditionState];
